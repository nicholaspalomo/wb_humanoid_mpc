"""Embeds the MuJoCo web viewer's page in a C++ source file, as a raw string literal behind webViewerPage().

The genrule of robot_runtime/web_viewer/BUILD.bazel runs it:

    embed_page --input page/index.html --output WebViewerPage.cpp

so the page stays a checked-in HTML file, editable and diffable as HTML, and no constant is defined in a header.
"""

import argparse
from collections.abc import Sequence
import sys

# The raw string delimiters to try, in order: the first whose terminator `)<delimiter>"` the page does not contain is
# used. C++ allows up to 16 characters, without spaces, parentheses and backslashes.
DELIMITERS = (
    "page",
    "html",
    "web_viewer",
    "embedded_page",
    "viewer_page_0",
    "viewer_page_1",
)
# The longest page: ISO C++ guarantees string literals of 65,536 characters (with the terminating NUL), and GCC warns
# about longer ones (-Woverlength-strings).
MAX_PAGE_BYTES = 65535

_SOURCE_TEMPLATE = """\
// Generated by robot_runtime/web_viewer/tools/embed_page.py from {page_path}: edit the page, not this file.

#include "web_viewer/WebViewerPage.h"

#include "absl/strings/string_view.h"

namespace robot::web_viewer {{

absl::string_view webViewerPage() {{
  static constexpr char kPage[] = R"{delimiter}({page}){delimiter}";
  return absl::string_view(kPage, sizeof(kPage) - 1);
}}

}}  // namespace robot::web_viewer
"""


class EmbedError(Exception):
    """A page that cannot be embedded: too long, holding a NUL, or containing the terminator of every delimiter."""


def choose_delimiter(page: str) -> str:
    """Returns the first of DELIMITERS whose raw string terminator does not occur in `page`.

    Args:
      page: The page's text.

    Returns:
      The delimiter.

    Raises:
      EmbedError: The page contains every terminator.
    """
    for delimiter in DELIMITERS:
        if f'){delimiter}"' not in page:
            return delimiter
    raise EmbedError(
        "the page contains the raw string terminator of every delimiter in DELIMITERS "
        f"({', '.join(DELIMITERS)}): add another one to tools/embed_page.py"
    )


def render_source(page: str, page_path: str) -> str:
    """Returns the C++ source that defines webViewerPage() over `page`.

    Args:
      page: The page's text.
      page_path: The page's path, for the generated file's comment.

    Returns:
      The text of WebViewerPage.cpp.

    Raises:
      EmbedError: The page cannot be a C++ string literal.
    """
    size = len(page.encode("utf-8"))
    if size > MAX_PAGE_BYTES:
        raise EmbedError(
            f"{page_path} has {size} bytes, more than the {MAX_PAGE_BYTES} a C++ string literal may hold: "
            "make it smaller"
        )
    if "\0" in page:
        raise EmbedError(f"{page_path} contains a NUL character")
    return _SOURCE_TEMPLATE.format(
        page_path=page_path, delimiter=choose_delimiter(page), page=page
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Reads the page and writes the C++ source; returns the exit status."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input", required=True, help="the page, page/index.html")
    parser.add_argument("--output", required=True, help="the C++ source to write")
    parser.add_argument(
        "--page_path",
        default="robot_runtime/web_viewer/page/index.html",
        help="the page's path in the repository, for the generated comment",
    )
    args = parser.parse_args(argv)
    with open(args.input, encoding="utf-8") as page_file:
        page = page_file.read()
    try:
        source = render_source(page, args.page_path)
    except EmbedError as error:
        print(f"embed_page: {error}", file=sys.stderr)
        return 1
    with open(args.output, "w", encoding="utf-8") as source_file:
        source_file.write(source)
    return 0


if __name__ == "__main__":
    sys.exit(main())
