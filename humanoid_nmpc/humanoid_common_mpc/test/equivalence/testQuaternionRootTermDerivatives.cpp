/*
 * The production terms of both MPCs, taped and generated by CppAD on the quaternion root joint, against double
 * precision, on every shipped configuration (MpcEquivalenceFixture: the MPC its shipped files build, under the walking
 * reference of walkingReference()): at points built from the task file's initial state - level, single- and two-axis
 * tilts, headings of 2.5 and -3.0 rad with a tilt of 0.05 rad, a pitch of 80 degrees, a seeded random state and the
 * middle of both single supports of the walk - and at the initial state at rest and at the two gimbal-lock attitudes
 * the Euler coordinates cannot represent (pitch +-90 degrees), every term of the optimal control problem - each cost,
 * soft constraint and constraint, intermediate and final - and the flow map are differentiated by
 * Richardson-extrapolated central differences of their double-precision values, along the state manifold's retraction
 * x (+) dx in every tangent direction and along every input, and the differences are held to the derivatives the terms
 * report, pulled back into the tangent (J E(x)), at every point. That covers every CppAD library's first order: the
 * dynamics, the Gauss-Newton costs' residual Jacobians and the CppAD constraints, all generated at first order
 * (CppAdInterface::ApproximationOrder::First everywhere in the MPCs; a Gauss-Newton Hessian is the product J' W J of a
 * first-order library). Where a term does generate a second order - a constraint of ConstraintOrder::Quadratic - its
 * input Hessians d2c/du2 and d2c/dudx are held to differences of its input Jacobian. The piecewise polynomial barriers,
 * which those points leave in their zero region, are held at two more points inside their bands (barrierBandPoints():
 * the joint limits and the basis scalings at the initial point, the foot collision at the right foot's mid-swing point
 * with the feet or the knees moved together). Every term of every collection, the pre-jump ones included, must be
 * checked at one point at least (coverageFindings()) and at one where its reported first derivative is not zero, so that
 * its check is not of zeros (nonZeroFindings()); a term no point can reach is exempted by name with the reason. The ICP
 * cost, unweighted (icp_error_weight 0) on every shipped robot, is weighed in the test's copy of the problem for the same
 * reason. The points are TermProbePoints.h's; testQuaternionRootTermHessians.cpp, in the same binary, holds every
 * cost's and soft constraint's second order there.
 *
 * One term reports a state Jacobian that is not its derivative, by design: the stance feet's twist constraint
 * (EndEffectorKinematicsTwistConstraint, which the centroidal MPC's zero-velocity constraint ZeroVelocityConstraintCppAd
 * evaluates; the whole body's ZeroAccelerationConstraintCppAd has no such map and is held as every term). Its value is
 *   f(x, u) = b + Ax [p(x); e(x)] + Av_lin v(x, u) + Av_ang M(x) w(x, u),
 * p, v and w the foot's position and world-frame (LOCAL_WORLD_ALIGNED) linear and angular velocity, e its orientation
 * error to the ground plane, e = -(v_n x n) / sqrt(2 (1 + v_n.n)) for the foot normal v_n and the plane normal n, and
 * M(x) = de/dw (plus 1/2 n v_n' where the yaw rate about the normal is constrained) the map from the angular velocity
 * to the rate of the residual (getAngularVelocityToOrientationErrorRateMap()). getLinearApproximation() holds M at its
 * value at the point, so it reports
 *   J = Ax [dp/dx; de/dx] + Av_lin dv/dx + Av_ang M(x) dw/dx,     dfdu = Av_lin dv/du + Av_ang M(x) dw/du,
 * whose input Jacobian is exact (M reads no input) and whose state Jacobian lacks the product rule's other half: along
 * the retraction, d/ds f(x (+) s e_i, u) = J E(x) e_i + D_i with
 *   D_i = Av_ang (d/ds M(x (+) s e_i)) w(x, u),
 * which vanishes where the foot does not turn, and for a soft constraint L = sum_i p(f_i) the gradient lacks p'(f)' D.
 * No shipped robot lists the soft form, so the test adds it to its copy of the problem (addSoftStanceFootConstraint()):
 * the first stance foot's hard constraint wrapped as CentroidalMpcInterface wraps it under zero_velocity, a
 * StateInputSoftConstraint with a QuadraticPenalty of the foot constraint's soft_constraint_weight, held as the hard one
 * with D contracted with p'(f).
 * The test computes D independently of f - M differenced along the same retraction, contracted with w, the angular part
 * of the foot's twist at the point, its own value - and holds, at every point of the twist constraint:
 *   (a) J E + D to the differences of f (those of (b)) within kDerivativeTolerance, as every term (at the points at
 *       rest, where w = 0 and so D = 0 exactly, J E alone: the reported Jacobian is the derivative there);
 *   (b) J E + D to them entry by entry within the error bound of the two differences - extrapolate() at
 *       h = kBoundedDifferenceStep, for f and for M alike: each one's Richardson estimate |R(h/2) - R(h)| plus its
 *       round-off 6 delta / h, delta = kFunctionEvaluationRelativeError of each row's largest magnitude, floor 1 - plus
 *       the reported Jacobian's round-off, kRoundOffFactor of its row's largest magnitude, floor 1; and that comparison
 *       must reject D with its largest entry moved by kDroppedTermMutation (1e-6) of max(1, itself), which a bound at
 *       the level of kDerivativeTolerance could not - for the soft form, whose bound grows with its value L, the floor
 *       of 1 is raised to its penalty's steepest slope max |p'(f_r)|, what its gradient sees of a unit change of the
 *       constraint's own D. So the reported Jacobian differs from the derivative by D and by nothing else, to that
 *       resolution: on the shipped robots the hard constraint's by at most 2e-12 of the Jacobian's scale, under a
 *       thousandth of the bound, which rejects every mutation of it by a factor of 12 at least (the summary prints
 *       each point's factor, the soft form's too);
 *   (c) the map against the rate of the residual along the motion, P M(x) w(x, u) = de/dx f_a(x, u) with P = I - n n'
 *       and f_a the ambient flow map, within kFunctionEvaluationRelativeError of the magnitudes of the summands of both
 *       sides: the tilt rows of the constraint are the PD law Kp e + Kd de/dt they claim, in the frame w is in.
 *
 * How large D is, and why. D is linear in w: up to about 5 % of the Jacobian's scale per rad/s of the foot on the SA01,
 * G1 and R1 (Kd = 1), up to 0.1 % on the Atlas (Kd = 0.01). At the points in motion built from the walk the feet turn at
 * 0.05 to 0.26 rad/s, driven by the inputs' joint velocities (each drawn within 0.1 rad/s), and D is at most 1 % of the
 * scale. random_0 also draws each normalized momentum within 0.2, and its angular part L / m (m^2 / s) turns the whole
 * robot at I_G^-1 L, fastest about the vertical, where a humanoid's inertia per mass is smallest (I_zz / m about
 * 0.0135 m^2 on the G1 at its neutral configuration, against about 0.1 m^2 about the horizontal axes, which cannot give
 * more than 2 rad/s): the G1's draw - each robot draws its own, the generator's position depending on the robot's
 * dimensions - spins it at 13.5 rad/s about the vertical with both feet in stance, where D is 64 % of the scale; the
 * other robots' draws turn them at 0.7 to 2.3 rad/s. That is a stress point for the derivatives, not a stance the MPC
 * visits. At a solution the zero-velocity rows hold Kp e + Kd M w = 0: a flat stance foot (e = 0) has M w = 0, so w = 0
 * and D = 0 where the yaw rate about the normal is constrained (position_and_orientation, the Atlas), while the
 * tilt-only constraint (position_and_tilt) leaves the pivot rate w_n about the foot normal v_n to the other terms, and
 * then D = -w_n Av_ang M (dv_n/dx) (from M(x) v_n(x) = 0), first order in w_n; a tilted foot turns at about
 * (Kp / Kd) times its tilt. The summary prints, per foot, the largest D relative to max(1, max |J E + D|), and the foot's
 * angular speed and D at every point (humanoid_nmpc/docs/quaternion_base_orientation/README.md, section 2.8.5).
 */

